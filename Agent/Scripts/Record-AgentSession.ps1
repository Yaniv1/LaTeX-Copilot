[CmdletBinding()]
param(
    [Parameter(Mandatory = $true)]
    [string]$PaperPath,
    [string]$SessionId = $env:COPILOT_AGENT_SESSION_ID
)

$ErrorActionPreference = 'Stop'
Set-StrictMode -Version Latest

Import-Module (Join-Path $PSScriptRoot 'LaTeXCopilot.psm1') -Force
$workspace = Resolve-PaperWorkspace -PaperPath $PaperPath
if ([string]::IsNullOrWhiteSpace($SessionId)) {
    throw 'COPILOT_AGENT_SESSION_ID is unavailable. Provide -SessionId explicitly.'
}
if ($SessionId -notmatch '^[A-Za-z0-9][A-Za-z0-9._-]*$') {
    throw 'The Copilot session ID contains unsupported characters.'
}

$configurationPath = Join-Path $workspace 'Authoring\config.json'
$configuration = Get-PaperConfiguration -PaperPath $workspace
if ($configuration.PSObject.Properties.Name -notcontains 'agentSession') {
    $configuration | Add-Member -NotePropertyName agentSession -NotePropertyValue ([pscustomobject]@{})
}

$startedAtUtc = [DateTime]::UtcNow
$startedAtPst = $startedAtUtc.AddHours(-8)
$sessionRecord = [pscustomobject]@{
    sessionId = $SessionId
    startedAtUtc = $startedAtUtc.ToString('o')
    startedAtPst = $startedAtPst.ToString('yyyy-MM-dd HH:mm') + ' PST'
}

$history = @()
if ($configuration.agentSession.PSObject.Properties.Name -contains 'history') {
    $history = @($configuration.agentSession.history)
}
$history = @($history | Where-Object { [string]$_.sessionId -ne $SessionId })
$history += $sessionRecord

$configuration.agentSession | Add-Member -Force -NotePropertyName activeSessionId -NotePropertyValue $SessionId
$configuration.agentSession | Add-Member -Force -NotePropertyName lastStartedAtUtc -NotePropertyValue $sessionRecord.startedAtUtc
$configuration.agentSession | Add-Member -Force -NotePropertyName lastStartedAtPst -NotePropertyValue $sessionRecord.startedAtPst
$configuration.agentSession | Add-Member -Force -NotePropertyName resumeCommand -NotePropertyValue "/resume $SessionId"
$configuration.agentSession | Add-Member -Force -NotePropertyName history -NotePropertyValue @($history)
Write-JsonAtomic -Path $configurationPath -Value $configuration

$instructionPath = Join-Path $workspace 'Authoring\instructions\agent-session.md'
$instruction = @"
# Agent Session Recovery

The active LaTeX-CoPilot session ID is ``$SessionId``.

It was last recorded at $($sessionRecord.startedAtPst).

If the agent instance crashes or disappears, start GitHub Copilot CLI and run:

~~~text
/resume $SessionId
~~~

This file is generated by ``Record-AgentSession.ps1`` whenever an agent
instance starts working on this paper.
"@
Set-Content -LiteralPath $instructionPath -Value $instruction -Encoding UTF8

Write-Host "Recorded LaTeX-CoPilot session: $SessionId"
Write-Host "Resume with: /resume $SessionId"
